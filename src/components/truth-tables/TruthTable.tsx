import { type ReactNode, useRef } from 'react';
import { useScrollable } from '@/components/useScrollable';
import type { Bit } from '@/lib/logic/types';

export interface TTColumn {
  key: string;
  header: ReactNode;
  /** Used for aria labels. */
  name: string;
  kind: 'input' | 'mid' | 'output';
}

interface Props {
  columns: TTColumn[];
  rows: { icn: number; cells: Record<string, Bit | null | ReactNode> }[];
  highlight?: number | null;
  onRowSelect?: (index: number) => void;
  caption?: ReactNode;
  showICN?: boolean;
  compact?: boolean;
}

function Cell({ value, kind }: { value: Bit | null | ReactNode; kind: TTColumn['kind'] }) {
  if (value === 1 || value === 0) {
    const on = value === 1;
    if (kind === 'output') {
      return (
        <span className={`inline-flex h-7 w-7 items-center justify-center rounded-md font-mono font-semibold ${on ? 'bg-hi text-[#1d1400]' : 'border border-lo text-lo-ink'}`}>
          {value}
        </span>
      );
    }
    return <span className={`font-mono ${on ? 'font-semibold text-ink' : 'text-ink-3'}`}>{value}</span>;
  }
  if (value === null || value === undefined) return <span className="text-ink-3">–</span>;
  return <>{value}</>;
}

/**
 * Truth table display. Rows are generated by the engine and passed in; this
 * component never computes logic itself.
 */
export function TruthTable({ columns, rows, highlight, onRowSelect, caption, showICN = true, compact }: Props) {
  const pad = compact ? 'px-2 py-1' : 'px-3 py-1.5';
  const scrollRef = useRef<HTMLDivElement>(null);
  const scrollable = useScrollable(scrollRef);
  return (
    <div ref={scrollRef} tabIndex={scrollable ? 0 : undefined} role={scrollable ? 'region' : undefined} aria-label={scrollable ? 'Truth table, scrolls sideways' : undefined} className="table-scroll rounded-xl border border-line bg-surface">
      <table className="w-full border-collapse text-center text-[0.95rem]">
        {caption && <caption className="px-3 pt-2 text-left text-sm text-ink-2 caption-top">{caption}</caption>}
        <thead>
          <tr className="border-b-2 border-line-strong bg-surface-2">
            {showICN && (
              <th scope="col" className={`${pad} sticky left-0 bg-surface-2 font-mono text-xs font-semibold text-ink-3`}>
                ICN
              </th>
            )}
            {columns.map((c, i) => {
              const firstMid = c.kind !== 'input' && columns[i - 1]?.kind === 'input';
              const firstOut = c.kind === 'output' && columns[i - 1]?.kind !== 'output';
              return (
                <th
                  key={c.key}
                  scope="col"
                  className={`${pad} whitespace-nowrap font-semibold ${c.kind === 'output' ? 'text-ink' : c.kind === 'mid' ? 'text-ink-2' : 'text-ink'} ${
                    firstMid || firstOut ? 'border-l-2 border-line-strong' : ''
                  }`}
                >
                  {c.header}
                </th>
              );
            })}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, idx) => {
            const active = highlight === idx;
            return (
              <tr
                key={r.icn}
                onClick={onRowSelect ? () => onRowSelect(idx) : undefined}
                className={`border-b border-line last:border-0 ${active ? 'bg-hi-soft' : idx % 2 ? 'bg-surface' : 'bg-paper/40'} ${onRowSelect ? 'cursor-pointer hover:bg-surface-2' : ''}`}
                aria-selected={onRowSelect ? active : undefined}
              >
                {showICN && (
                  <td className={`${pad} sticky left-0 font-mono text-xs text-ink-3 ${active ? 'bg-hi-soft' : 'bg-inherit'}`}>
                    {onRowSelect ? (
                      <button type="button" className="rounded px-1 underline-offset-2 hover:underline" onClick={() => onRowSelect(idx)} aria-label={`Show row ${r.icn}`}>
                        {r.icn}
                      </button>
                    ) : (
                      r.icn
                    )}
                  </td>
                )}
                {columns.map((c, i) => {
                  const firstMid = c.kind !== 'input' && columns[i - 1]?.kind === 'input';
                  const firstOut = c.kind === 'output' && columns[i - 1]?.kind !== 'output';
                  return (
                    <td key={c.key} className={`${pad} ${firstMid || firstOut ? 'border-l-2 border-line-strong' : ''}`}>
                      <Cell value={r.cells[c.key] as Bit | null} kind={c.kind} />
                    </td>
                  );
                })}
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}
